-- Lissurary — Supabase(PostgreSQL) 스키마
--
-- app/database.py의 SQLAlchemy 모델(Student/Schedule/ScheduleRevision/
-- SystemSetting/ScheduleAudit/ScheduleRun)과 1:1로 대응하는 DDL이다.
-- 컬럼명/타입/제약조건은 ORM 정의를 그대로 옮긴 것이며, 앱이 사용하는 것
-- 이상의 컬럼·제약·RLS는 추가하지 않는다(Supabase는 순수 DB 호스팅으로만
-- 사용 — docs/architecture.md 참고, Auth/RLS 미사용).
--
-- ⚠️ 이 파일은 선택 사항이다. 앱이 기동될 때 app/database.py의 init_database()가
-- Base.metadata.create_all(engine)을 호출해 아래와 동일한 테이블을 자동 생성한다
-- (LISSURARY_배포가이드.md 2번 참고). 배포 전에 Supabase Studio에서 스키마를 미리
-- 검토·생성하고 싶을 때만 이 SQL을 SQL Editor에서 실행하면 된다 — 실행 안 해도
-- DATABASE_URL만 올바르면 첫 기동 시 동일하게 만들어진다.

-- students: 근로생 명단 (app/database.py Student)
create table if not exists public.students (
    id          integer generated by default as identity primary key,
    name        varchar(80) not null,
    student_no  varchar(30) not null,
    work_type   varchar(5) not null default '',
    active      boolean not null default true,
    constraint students_student_no_key unique (student_no)
);
create index if not exists ix_students_name on public.students (name);
create index if not exists ix_students_active on public.students (active);

-- schedules: 학생 1인당 최신 희망 스케줄 1개 (app/database.py Schedule)
create table if not exists public.schedules (
    id             integer generated by default as identity primary key,
    student_id     integer not null references public.students (id),
    schedule_json  text not null,
    state          varchar(20) not null default 'draft',
    saved_at       timestamptz not null,
    submitted_at   timestamptz null,
    constraint schedules_student_id_key unique (student_id)
);
create index if not exists ix_schedules_state on public.schedules (state);

-- schedule_revisions: 스케줄 저장 이력(append-only, 감사용) (app/database.py ScheduleRevision)
create table if not exists public.schedule_revisions (
    id             integer generated by default as identity primary key,
    student_id     integer not null references public.students (id),
    schedule_json  text not null,
    state          varchar(20) not null,
    created_at     timestamptz not null
);
create index if not exists ix_schedule_revisions_student_id on public.schedule_revisions (student_id);
create index if not exists ix_schedule_revisions_state on public.schedule_revisions (state);
create index if not exists ix_schedule_revisions_created_at on public.schedule_revisions (created_at);

-- system_settings: 범용 key-value 설정 저장소 (app/database.py SystemSetting)
-- v4.7 기준 실제 사용하는 key: student_access_start_utc, student_access_end_utc,
-- student_access_manual_lock (학생 입력기간 시작/마감/수동잠금 여부)
create table if not exists public.system_settings (
    key    varchar(80) primary key,
    value  text not null default ''
);

-- schedule_audits: 스케줄 변경 감사 로그 — 누가(학생 본인/관리자) 바꿨는지 기록
-- (app/database.py ScheduleAudit)
create table if not exists public.schedule_audits (
    id             integer generated by default as identity primary key,
    student_id     integer not null references public.students (id),
    actor_type     varchar(20) not null,
    actor_id       varchar(80) not null default '',
    state          varchar(20) not null,
    schedule_json  text not null,
    created_at     timestamptz not null
);
create index if not exists ix_schedule_audits_student_id on public.schedule_audits (student_id);
create index if not exists ix_schedule_audits_actor_type on public.schedule_audits (actor_type);
create index if not exists ix_schedule_audits_state on public.schedule_audits (state);
create index if not exists ix_schedule_audits_created_at on public.schedule_audits (created_at);

-- schedule_runs: 전체/데스크 시간표 생성 결과 스냅샷 (app/database.py ScheduleRun)
create table if not exists public.schedule_runs (
    id                     integer generated by default as identity primary key,
    full_schedule_json     text not null,
    desk_schedule_json     text not null,
    student_summary_json   text not null,
    summary_json           text not null,
    created_at             timestamptz not null
);
create index if not exists ix_schedule_runs_created_at on public.schedule_runs (created_at);
